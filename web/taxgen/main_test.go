// TestTypesUnionMirrorsCategories pins the generated TypeScript union:
// exactly one member per canonical category, in tooltax's display order,
// and nothing invented locally. This union is what makes a missing
// colour a COMPILE error in actions.ts, so a union that silently lost a
// member would re-open the hole it exists to close.
func TestTypesUnionMirrorsCategories(t *testing.T) {
	src := generateTypesOrFail(t)

	if !strings.Contains(src, "DO NOT EDIT") {
		t.Error("generated .ts has no DO NOT EDIT marker")
	}
	if !strings.Contains(src, "export type ActionCategory =\n") {
		t.Fatalf("generated .ts does not declare ActionCategory:\n%s", src)
	}
	if !strings.HasSuffix(src, "\n") || strings.HasSuffix(src, "\n\n") {
		t.Error("generated .ts does not end with exactly one newline")
	}

	var members []string
	for _, line := range strings.Split(src, "\n") {
		if !strings.HasPrefix(line, "  | ") {
			continue
		}
		member := strings.TrimSuffix(strings.TrimPrefix(line, "  | "), ";")
		unquoted, err := strconv.Unquote(member)
		if err != nil {
			t.Fatalf("union member %q is not a quoted string: %v", member, err)
		}
		members = append(members, unquoted)
	}

	want := tooltax.Categories()
	if strings.Join(members, ",") != strings.Join(want, ",") {
		t.Errorf("union = [%s]; tooltax.Categories() = [%s]",
			strings.Join(members, ","), strings.Join(want, ","))
	}
	// Every member must be terminated correctly: only the last line
	// carries the semicolon, or tsc will not parse the file.
	if !strings.HasSuffix(strings.TrimRight(src, "\n"), strconv.Quote(want[len(want)-1])+";") {
		t.Errorf("union is not terminated with %q;\n%s", want[len(want)-1], src)
	}
}

// TestVectorsUseGoAsTheOracle is what makes the TypeScript gate a parity
// gate rather than a snapshot: every oracle=tooltax.MCPIdentity vector's
// expectation must be exactly what the Go parser returns for that row,
// recomputed here rather than trusted.
func TestVectorsUseGoAsTheOracle(t *testing.T) {
	v := generateVectorsOrFail(t)
	if len(v.Cases) == 0 {
		t.Fatal("no vectors emitted")
	}

	goCases := 0
	for _, c := range v.Cases {
		switch c.Oracle {
		case oracleGo:
			goCases++
			if c.Row.ActionType != nil {
				t.Errorf("%s: a Go-oracle vector must not set action_type — "+
					"the Go parser has no such input", c.Name)
			}
			if c.Row.Target != nil {
				t.Errorf("%s: a Go-oracle vector must not set target — "+
					"tooltax.MCPIdentity parses raw names only", c.Name)
			}
			if c.Row.RawToolName == nil {
				t.Errorf("%s: a Go-oracle vector must set raw_tool_name", c.Name)
				continue
			}
			server, tool, ok := tooltax.MCPIdentity(*c.Row.RawToolName)
			if !ok {
				if c.Want != nil {
					t.Errorf("%s: want %+v, but tooltax.MCPIdentity rejects the name",
						c.Name, *c.Want)
				}
				continue
			}
			if c.Want == nil {
				t.Errorf("%s: want null, but tooltax.MCPIdentity gives (%q, %q)",
					c.Name, server, tool)
				continue
			}
			if c.Want.Server != server || c.Want.Tool != tool {
				t.Errorf("%s: want (%q, %q); tooltax.MCPIdentity gives (%q, %q)",
					c.Name, c.Want.Server, c.Want.Tool, server, tool)
			}
		case oracleTSGuard:
			// No Go counterpart by construction — the expectation is the
			// declared contract for the TS-only path/URL guards. All we
			// can pin here is that it IS declared as such.
			if c.Row.ActionType == nil && c.Row.RawToolName == nil && c.Row.Target == nil {
				continue // the deliberate empty-row case
			}
		default:
			t.Errorf("%s: unknown oracle %q", c.Name, c.Oracle)
		}
	}
	if goCases == 0 {
		t.Error("no Go-oracle vectors — the TS gate would pin nothing that Go owns")
	}
}

// TestVectorsCoverTheKnownTraps pins the specific rows this gate exists
// for: the degenerate name that used to diverge, the colon form on both
// carriers, and the three path shapes finding 3 identified.
func TestVectorsCoverTheKnownTraps(t *testing.T) {
	v := generateVectorsOrFail(t)

	rawSeen := make(map[string]struct{})
	targetSeen := make(map[string]struct{})
	for _, c := range v.Cases {
		if c.Row.RawToolName != nil {
			rawSeen[*c.Row.RawToolName] = struct{}{}
		}
		if c.Row.Target != nil {
			targetSeen[*c.Row.Target] = struct{}{}
		}
	}
	for _, raw := range []string{"mcp____tool", "mcp__observer__get_file", "node_repl:js"} {
		if _, ok := rawSeen[raw]; !ok {
			t.Errorf("no vector carries raw_tool_name %q", raw)
		}
	}
	for _, target := range []string{
		`C:\repo\file.txt`,
		"C:/repo/file.txt",
		"/tmp/socket:query",
		"https://example.com/x",
		"observer:get_session_summary",
	} {
		if _, ok := targetSeen[target]; !ok {
			t.Errorf("no vector carries target %q", target)
		}
	}

	// The degenerate case must carry Go's answer, not the pre-WP-T2
	// TypeScript one — written out by hand so a change on EITHER side is
	// loud.
	for _, c := range v.Cases {
		if c.Row.RawToolName == nil || *c.Row.RawToolName != "mcp____tool" {
			continue
		}
		if c.Want == nil || c.Want.Server != "__tool" || c.Want.Tool != "" {
			t.Errorf("the mcp____tool vector expects %+v; want {__tool, \"\"} — "+
				"Go's behaviour, which WP-T2 aligned TypeScript onto", c.Want)
		}
	}
}

