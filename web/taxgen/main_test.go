// TestToolCoverageMirrorsTooltax pins the WP-T5 per-adapter capture-depth
// map: exactly the tools tooltax declares rows for, each with
// CategoriesForTool's answer verbatim, and every category drawn from the
// emitted canonical list.
func TestToolCoverageMirrorsTooltax(t *testing.T) {
	d := decodeOrFail(t, generateOrFail(t))
	tools := tooltax.Tools()
	if len(d.ToolCoverage) != len(tools) {
		t.Errorf("emitted coverage for %d tools, tooltax declares %d", len(d.ToolCoverage), len(tools))
	}
	known := make(map[string]struct{}, len(d.Categories))
	for _, c := range d.Categories {
		known[c] = struct{}{}
	}
	for _, tool := range tools {
		got, ok := d.ToolCoverage[tool]
		if !ok {
			t.Errorf("tool %q missing from the emitted coverage map", tool)
			continue
		}
		want := tooltax.CategoriesForTool(tool)
		if strings.Join(got.Categories, ",") != strings.Join(want, ",") {
			t.Errorf("tool %q coverage = [%s]; tooltax says [%s]",
				tool, strings.Join(got.Categories, ","), strings.Join(want, ","))
		}
		for _, c := range got.Categories {
			if _, ok := known[c]; !ok {
				t.Errorf("tool %q coverage has category %q, which is not in the emitted category list", tool, c)
			}
		}
	}
	// The honest zero: a tool with no declared vocabulary is ABSENT, not
	// present with an empty list, so the dashboard can tell "shallow
	// capture" from "not mapped yet". The five browser-rail `*-web` tools
	// are the live instance of that case.
	if _, ok := d.ToolCoverage["chatgpt-web"]; ok {
		t.Error("chatgpt-web has no tooltax rows but appears in the coverage map")
	}
}

// TestToolCoverageIsNotTheNativeTable pins the plan's §7 sizing decision:
// the emitted coverage map is the DERIVED per-tool category set (~30
// short arrays), never the ~1,074-row (tool, native) table, which the
// browser has no use for and which would be dead bundle weight.
func TestToolCoverageIsNotTheNativeTable(t *testing.T) {
	d := decodeOrFail(t, generateOrFail(t))
	maxCats := len(tooltax.Categories())
	for tool, cov := range d.ToolCoverage {
		if len(cov.Categories) > maxCats {
			t.Errorf("tool %q emitted %d entries; a coverage list cannot exceed the %d canonical categories",
				tool, len(cov.Categories), maxCats)
		}
	}
	// And no native tool NAME may appear in the emitted bytes. Sourced
	// from the table itself rather than hand-picked, minus the names that
	// legitimately coincide with a canonical action type (`read_file`,
	// `web_search`, …) or with a tool id, which the file does emit.
	data := generateOrFail(t)
	skip := map[string]struct{}{}
	for _, at := range tooltax.ActionTypes() {
		skip[at] = struct{}{}
	}
	for _, tool := range tooltax.Tools() {
		skip[tool] = struct{}{}
	}
	for _, c := range tooltax.Categories() {
		skip[c] = struct{}{}
	}
	for _, s := range tooltax.Surfaces() {
		skip[string(s)] = struct{}{}
	}
	leaked := 0
	for _, e := range tooltax.Table() {
		if _, ok := skip[e.Native]; ok {
			continue
		}
		if bytes.Contains(data, []byte(`"`+e.Native+`"`)) {
			if leaked < 5 {
				t.Errorf("native tool name %q leaked into the generated data file — the (tool, native) table must not be emitted", e.Native)
			}
			leaked++
		}
	}
	if leaked > 5 {
		t.Errorf("... and %d more native names leaked", leaked-5)
	}
}

// TestNewTaxonomyTypesRenderSensibly pins the eight action types WP-T1
// introduced to close the measured `unknown` gap. They are the reason
// this generator exists: before it, the dashboard humanized them into
// gray "meta" chips because its hand-maintained registry had never heard
