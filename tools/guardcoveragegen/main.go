// Command guardcoveragegen writes shared/lib/guardToolCoverage.generated.ts,
// the per-tool guard rule coverage the org guard form renders under a rule
// ("which tools block / ask / warn / record only for this decision").
//
// The data is internal/controlcoverage.RuleCoverage, derived from the
// capability registry's hook bindings, the prompt dialect rows
// (internal/hook) and the conformance matrix; this command only wires the
// internal/hook facts in and serializes the result, so the admin wording is
// generated from the same rows the hook receivers act on and never
// hand-maintained.
//
// USAGE
//
//	go run ./tools/guardcoveragegen          # rewrite the TS file
//	go run ./tools/guardcoveragegen -check   # drift gate: write nothing
//
// `make guard-coverage-ts` and
// `make verify-guard-coverage-ts` wrap the two forms
// (beside the adapter parity doc gate). The output is deterministic: tools
// sorted by id, no timestamps, no map iteration order.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"strings"

	"github.com/marmutapp/superbased-observer/internal/controlcoverage"
	"github.com/marmutapp/superbased-observer/internal/hook"
)

// defaultOut is the generated file's path relative to the repository root.
const defaultOut = "shared/lib/guardToolCoverage.generated.ts"

// errStale is returned by -check when the committed file differs.
var errStale = errors.New("generated guard coverage is stale: run 'make guard-coverage-ts' and commit")

func main() {
	out := flag.String("out", defaultOut, "path of the generated TS file")
	check := flag.Bool("check", false, "write nothing; exit non-zero when the file differs from a fresh render")
	flag.Parse()
	if err := run(*out, *check, os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "guardcoveragegen:", err)
		os.Exit(1)
	}
}

// run renders the file and writes it (check false) or compares it with the
// committed one (check true).
func run(path string, check bool, w io.Writer) error {
	next, err := render()
	if err != nil {
		return err
	}
	cur, err := os.ReadFile(path)
	if err != nil && !(errors.Is(err, os.ErrNotExist) && !check) {
		return fmt.Errorf("read %s: %w", path, err)
	}
	if bytes.Equal(cur, next) {
		fmt.Fprintf(w, "%s: up to date\n", path)
		return nil
	}
	if check {
		fmt.Fprintf(w, "%s: stale\n", path)
		return errStale
	}
	//nolint:gosec // G306: a committed source artifact; world-readable is intended.
	if err := os.WriteFile(path, next, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	fmt.Fprintf(w, "%s: written\n", path)
	return nil
}

// facts are internal/hook's per-dialect facts.
var facts = controlcoverage.RuleSeamFacts{
	PromptCaps:    hook.PromptDialectSeamCaps,
	ToolAskProbed: hook.ToolGateAskProbed,
}

// laneJSON / toolJSON are the wire shape of the TS data (camelCase keys).
type laneJSON struct {
	Seam    string   `json:"seam"`
	Event   string   `json:"event,omitempty"`
	Flag    string   `json:"flag"`
	Ask     string   `json:"ask"`
	Deny    string   `json:"deny"`
	Caveats []string `json:"caveats"`
}

type toolJSON struct {
	Tool     string   `json:"tool"`
	Name     string   `json:"name"`
	Prompt   laneJSON `json:"prompt"`
	ToolCall laneJSON `json:"toolCall"`
}

func laneOf(l controlcoverage.RuleLaneCoverage) laneJSON {
	cav := l.Caveats
	if cav == nil {
		cav = []string{}
	}
	return laneJSON{
		Seam: string(l.Seam), Event: l.Event,
		Flag: string(l.Flag), Ask: string(l.Ask), Deny: string(l.Deny),
		Caveats: cav,
	}
}

// seams is the closed seam vocabulary, in the order the type lists it.
var seams = []controlcoverage.RuleSeam{
	controlcoverage.RuleSeamHook, controlcoverage.RuleSeamProxy, controlcoverage.RuleSeamCapture, controlcoverage.RuleSeamNone,
}

const header = `// Code generated by tools/guardcoveragegen from
// internal/controlcoverage.RuleCoverage. DO NOT EDIT.
//
// Regenerate with ` + "`make guard-coverage-ts`" + `; the
// ` + "`verify-guard-coverage-ts`" + ` drift gate (ci-private.yml) fails until the
// regenerated file is committed. The data comes from the capability
// registry's hook bindings, the prompt dialect rows and the conformance
// matrix: what a developer experiences on each tool when a guard rule
// resolves to flag, ask or deny. Rendering helpers live in
// guardToolCoverage.ts.
`

// render builds the TS file.
func render() ([]byte, error) {
	rows := controlcoverage.RuleCoverage(facts)
	tools := make([]toolJSON, 0, len(rows))
	for _, r := range rows {
		tools = append(tools, toolJSON{Tool: r.Tool, Name: r.Name, Prompt: laneOf(r.Prompt), ToolCall: laneOf(r.ToolCall)})
	}
	data, err := marshal(tools)
	if err != nil {
		return nil, err
	}
	outcomes := make([]string, 0)
	for _, o := range controlcoverage.RuleOutcomes() {
		outcomes = append(outcomes, fmt.Sprintf("%q", string(o)))
	}
	seamLits := make([]string, 0, len(seams))
	for _, s := range seams {
		seamLits = append(seamLits, fmt.Sprintf("%q", string(s)))
	}
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\n/** The outcome vocabulary, strongest first. */\n")
	b.WriteString("export const GUARD_COVERAGE_OUTCOMES = [" + strings.Join(outcomes, ", ") + "] as const;\n\n")
	b.WriteString("/** What the developer experiences for one rule decision on one tool. */\n")
	b.WriteString("export type GuardCoverageOutcome = (typeof GUARD_COVERAGE_OUTCOMES)[number];\n\n")
	b.WriteString("/** The lane that produces the outcome. */\n")
	b.WriteString("export type GuardCoverageSeam = " + strings.Join(seamLits, " | ") + ";\n\n")
	b.WriteString("/** One lane's answer for one tool. */\n")
	b.WriteString("export type GuardLaneCoverage = {\n  seam: GuardCoverageSeam;\n  event?: string;\n  flag: GuardCoverageOutcome;\n  ask: GuardCoverageOutcome;\n  deny: GuardCoverageOutcome;\n  caveats: string[];\n};\n\n")
	b.WriteString("/** One tool's rule coverage on the prompt and tool-call lanes. */\n")
	b.WriteString("export type GuardToolCoverage = {\n  tool: string;\n  name: string;\n  prompt: GuardLaneCoverage;\n  toolCall: GuardLaneCoverage;\n};\n\n")
	b.WriteString("export const GUARD_TOOL_COVERAGE: readonly GuardToolCoverage[] = ")
	b.Write(data)
	b.WriteString(";\n")
	return []byte(b.String()), nil
}

// marshal encodes v as indented JSON without HTML escaping.
func marshal(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		return nil, fmt.Errorf("encode coverage: %w", err)
	}
	return bytes.TrimRight(buf.Bytes(), "\n"), nil
}
