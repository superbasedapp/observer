package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

// generate reads the vendored upstream files (checked against UPSTREAM),
// builds the tables and returns the formatted Go source of the generated
// file. It is a pure function of the files' bytes: the same input always
// gives the same output, which is what the drift test relies on.
func generate(upstreamDir string) ([]byte, error) {
	m, err := readManifest(upstreamDir)
	if err != nil {
		return nil, err
	}
	files, err := loadUpstream(upstreamDir, m)
	if err != nil {
		return nil, err
	}
	t, err := buildTables(files)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	emitHeader(&b, m, files["LICENSE"])
	emitProvenance(&b, m)
	emitBaseMetrics(&b, t)
	emitKnownMetrics(&b, t)
	emitLevels(&b, t)
	emitDefaults(&b)
	emitMacro(&b, t)
	emitMaxSeverity(&b, t)
	emitComposed(&b, t)
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("cvss4gen.generate: gofmt the output: %w\n%s", err, b.String())
	}
	return src, nil
}

func commentBlock(b *bytes.Buffer, text string) {
	for _, line := range strings.Split(strings.TrimRight(text, "\n"), "\n") {
		if line == "" {
			b.WriteString("//\n")
		} else {
			b.WriteString("// " + line + "\n")
		}
	}
}

func emitHeader(b *bytes.Buffer, m *manifest, license string) {
	b.WriteString("// Code generated by tools/cvss4gen from FIRST's CVSS 4.0 calculator data; DO NOT EDIT.\n")
	b.WriteString("//\n")
	fmt.Fprintf(b, "// Source:  %s\n", m.Repo)
	fmt.Fprintf(b, "// Branch:  %s\n", m.Branch)
	fmt.Fprintf(b, "// Commit:  %s (%s)\n", m.Commit, m.CommitDate)
	b.WriteString("// Files (sha256 of the exact bytes the tables were generated from):\n")
	for _, f := range m.Files {
		fmt.Fprintf(b, "//   %-16s %s\n", f.Name, f.SHA256)
	}
	b.WriteString("//\n")
	b.WriteString("// Regenerate with `go generate ./internal/secassess/cvss4`; tools/cvss4gen's\n")
	b.WriteString("// drift test fails if this file and the vendored upstream files disagree.\n")
	b.WriteString("//\n")
	fmt.Fprintf(b, "// The data below is derived from the files above, which are licensed %s.\n", m.License)
	b.WriteString("// The upstream licence is reproduced here, unchanged, as it requires:\n")
	b.WriteString("//\n")
	commentBlock(b, license)
	b.WriteString("\npackage cvss4\n\n")
}

func emitProvenance(b *bytes.Buffer, m *manifest) {
	b.WriteString("// Upstream provenance of the tables in this file.\n")
	b.WriteString("const (\n")
	fmt.Fprintf(b, "\t// UpstreamRepo is the repository the tables were generated from.\n\tUpstreamRepo = %q\n", m.Repo)
	fmt.Fprintf(b, "\t// UpstreamCommit is the exact commit of that repository.\n\tUpstreamCommit = %q\n", m.Commit)
	fmt.Fprintf(b, "\t// UpstreamLicense is the licence of the upstream data.\n\tUpstreamLicense = %q\n", m.License)
	b.WriteString(")\n\n")
}

func emitBaseMetrics(b *bytes.Buffer, t *tables) {
	b.WriteString("// baseMetricDefs are the base metrics in vector order with the values each\n")
	b.WriteString("// may take, in upstream's order (cvss_config.js).\n")
	b.WriteString("var baseMetricDefs = []baseMetricDef{\n")
	for _, m := range t.BaseMetrics {
		var vals []string
		for _, v := range m.Values {
			vals = append(vals, fmt.Sprintf("%q", v))
		}
		fmt.Fprintf(b, "\t{Key: %q, Values: []string{%s}},\n", m.Key, strings.Join(vals, ", "))
	}
	b.WriteString("}\n\n")
}

func emitKnownMetrics(b *bytes.Buffer, t *tables) {
	b.WriteString("// knownMetricKeys is every metric CVSS 4.0 defines (base, threat, environmental\n")
	b.WriteString("// and supplemental), in the order cvss_config.js lists them. The parser uses it\n")
	b.WriteString("// to tell a metric that is not a base metric from one that does not exist.\n")
	b.WriteString("var knownMetricKeys = []string{")
	for i, k := range t.AllMetrics {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%q", k)
	}
	b.WriteString("}\n\n")
}

func emitLevels(b *bytes.Buffer, t *tables) {
	b.WriteString("// severityLevels is the per-metric severity level of each value (cvss_score.js\n")
	b.WriteString("// *_levels): 0 is the most severe value of the metric, larger is milder. The\n")
	b.WriteString("// severity distance of a vector from a maximal vector is the difference of\n")
	b.WriteString("// these levels.\n")
	b.WriteString("var severityLevels = map[string]map[string]float64{\n")
	for _, lt := range t.Levels {
		fmt.Fprintf(b, "\t%q: {", lt.Metric)
		for i, r := range lt.Rows {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(b, "%q: %s", r.Value, r.Number)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
}

func emitDefaults(b *bytes.Buffer) {
	b.WriteString("// notDefinedDefaults is the value a metric takes when a vector does not\n")
	b.WriteString("// define it (cvss_score.js m()): Exploit Maturity (E) not defined is Attacked,\n")
	b.WriteString("// and the Confidentiality, Integrity and Availability Requirements (CR, IR,\n")
	b.WriteString("// AR) not defined are High. A base-only vector relies on all four.\n")
	b.WriteString("var notDefinedDefaults = map[string]string{\n")
	for _, d := range notDefinedDefaults {
		fmt.Fprintf(b, "\t%q: %q,\n", d.Metric, d.Value)
	}
	b.WriteString("}\n\n")
}

func emitMacro(b *bytes.Buffer, t *tables) {
	b.WriteString("// macroScores is the score of the highest-severity vector of each of the 270\n")
	b.WriteString("// valid MacroVectors (cvss_lookup.js). The key is the six EQ levels, EQ1 to EQ6,\n")
	b.WriteString("// as digits; the 54 combinations with EQ3 = 2 and EQ6 = 0 cannot occur and are\n")
	b.WriteString("// absent.\n")
	b.WriteString("var macroScores = map[string]float64{\n")
	for _, r := range t.Macro {
		fmt.Fprintf(b, "\t%q: %s,\n", r.Key, r.Number)
	}
	b.WriteString("}\n\n")
}

func emitIntMap(b *bytes.Buffer, name, doc string, rows []intRow) {
	fmt.Fprintf(b, "// %s\n", doc)
	fmt.Fprintf(b, "var %s = map[int]int{", name)
	for i, r := range rows {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%d: %d", r.Key, r.Value)
	}
	b.WriteString("}\n\n")
}

func emitMaxSeverity(b *bytes.Buffer, t *tables) {
	emitIntMap(b, "maxSeverityEQ1", "maxSeverityEQ1 is the maximal severity distance, plus one, within each EQ1 level\n// (max_severity.js eq1). The scorer multiplies it by 0.1.", t.MaxSeverity.EQ1)
	emitIntMap(b, "maxSeverityEQ2", "maxSeverityEQ2 is the same for EQ2 (max_severity.js eq2).", t.MaxSeverity.EQ2)
	b.WriteString("// maxSeverityEQ3EQ6 is the same for the joined (EQ3, EQ6) pair (max_severity.js\n// eq3eq6).\n")
	b.WriteString("var maxSeverityEQ3EQ6 = map[[2]int]int{")
	for i, r := range t.MaxSeverity.EQ3EQ6 {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "{%d, %d}: %d", r.EQ3, r.EQ6, r.Value)
	}
	b.WriteString("}\n\n")
	emitIntMap(b, "maxSeverityEQ4", "maxSeverityEQ4 is the same for EQ4 (max_severity.js eq4).", t.MaxSeverity.EQ4)
	emitIntMap(b, "maxSeverityEQ5", "maxSeverityEQ5 is the same for EQ5 (max_severity.js eq5). Upstream never\n// scales EQ5's distance (it is always zero); the table is kept for completeness.", t.MaxSeverity.EQ5)
}

func emitFragment(b *bytes.Buffer, f []fragmentRow) {
	b.WriteString("{")
	for i, r := range f {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "{%q, %q}", r.Metric, r.Value)
	}
	b.WriteString("}")
}

func emitGroups(b *bytes.Buffer, name, doc, keyType string, groups []composedGroup) {
	fmt.Fprintf(b, "// %s\n", doc)
	fmt.Fprintf(b, "var %s = map[%s][]fragment{\n", name, keyType)
	for _, g := range groups {
		fmt.Fprintf(b, "\t// %s: %s\n", g.Key, strings.Join(g.Source, "  "))
		key := g.Key
		if keyType == "[2]int" {
			key = "{" + strings.ReplaceAll(g.Key, ",", ", ") + "}"
		}
		fmt.Fprintf(b, "\t%s: {\n", key)
		for _, f := range g.Fragments {
			b.WriteString("\t\t")
			emitFragment(b, f)
			b.WriteString(",\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")
}

func emitComposed(b *bytes.Buffer, t *tables) {
	emitGroups(b, "maxComposedEQ1", "maxComposedEQ1 lists, per EQ1 level, the metric settings of its maximal\n// vectors (max_composed.js eq1).", "int", t.Composed.EQ1)
	emitGroups(b, "maxComposedEQ2", "maxComposedEQ2 is the same for EQ2 (max_composed.js eq2).", "int", t.Composed.EQ2)
	emitGroups(b, "maxComposedEQ3EQ6", "maxComposedEQ3EQ6 is the same for the joined (EQ3, EQ6) pair; its fragments fix\n// VC, VI, VA and the three requirements (max_composed.js eq3).", "[2]int", t.Composed.EQ3EQ6)
	emitGroups(b, "maxComposedEQ4", "maxComposedEQ4 is the same for EQ4 (max_composed.js eq4).", "int", t.Composed.EQ4)
	emitGroups(b, "maxComposedEQ5", "maxComposedEQ5 is the same for EQ5 (max_composed.js eq5).", "int", t.Composed.EQ5)
}
