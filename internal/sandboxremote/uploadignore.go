package sandboxremote

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"path"
	"strings"
)

// uploadignore.go is the default ignore set of a hosted upload of a folder
// that is not a git repository (decision SBXD-8, audit item H8): the cmd
// layer lists such a folder with git's own ignore machinery through a
// temporary git directory outside it (`git --git-dir=<temp>
// --work-tree=<folder> ls-files --others --exclude-standard
// --exclude-from=<this file>`), so the folder's own .gitignore files apply
// as in a repository and this table adds what a repository would normally
// already ignore. The listing is only the first filter: PlanManifest still
// leaves out credential-shaped files, links and oversized files, and caps the
// whole upload.
//
// Each row says why it is there. The rule for a row: the folder is
// reinstallable or regenerable from the rest of the tree (dependencies,
// build output, virtual environments, caches), version-control metadata
// (history never leaves the machine), a secret, or operating-system junk.
// A name that is also a common source folder (build/, vendor/, env/, lib/)
// is left out on purpose: an extra pattern in
// [terminal.sandbox.hosted].upload_ignore adds it for one machine, and a
// negated one ("!dist/") takes a default back out, because the extra
// patterns are written after these and git's last match wins.

// UploadIgnoreRule is one default ignore pattern (gitignore syntax) and the
// reason it is there.
type UploadIgnoreRule struct {
	Pattern string
	Why     string
}

// DefaultUploadIgnore is the default ignore set, in the order it is written.
var DefaultUploadIgnore = []UploadIgnoreRule{
	// Dependencies: reinstalled in the box from the manifest files that are
	// uploaded, and often larger than the project itself.
	{"node_modules/", "JavaScript dependencies (npm, yarn, pnpm), reinstallable from package.json"},
	{"bower_components/", "Bower dependencies, reinstallable from bower.json"},
	{".pnpm-store/", "pnpm's content store, a cache of downloaded packages"},
	{".terraform/", "Terraform's downloaded providers and modules, reinstalled by terraform init"},
	// Virtual environments: machine-specific interpreters and installed
	// packages that do not run on another machine anyway.
	{".venv/", "Python virtual environment (the venv default name)"},
	{"venv/", "Python virtual environment (the other common name)"},
	{"__pypackages__/", "PEP 582 local packages, reinstallable"},
	{".direnv/", "direnv's per-folder environment cache"},
	// Build output and caches: regenerated by the build, never source.
	{"__pycache__/", "Python bytecode cache"},
	{"*.py[cod]", "Python compiled files"},
	{"*.egg-info/", "Python packaging metadata, regenerated by the build"},
	{".tox/", "tox test environments"},
	{".nox/", "nox test environments"},
	{".mypy_cache/", "mypy's cache"},
	{".pytest_cache/", "pytest's cache"},
	{".ruff_cache/", "ruff's cache"},
	{".next/", "Next.js build output"},
	{".nuxt/", "Nuxt build output"},
	{".svelte-kit/", "SvelteKit build output"},
	{".turbo/", "Turborepo cache"},
	{".parcel-cache/", "Parcel cache"},
	{".gradle/", "Gradle's cache"},
	{"target/", "Rust (cargo) and Maven build output"},
	{"dist/", "the conventional JavaScript and Python package output"},
	// Version-control metadata: history never leaves the machine (the box
	// gets a fresh baseline repository of the uploaded tree).
	{".git/", "git metadata (PlanManifest excludes it as well)"},
	{".hg/", "Mercurial metadata"},
	{".svn/", "Subversion metadata"},
	{".bzr/", "Bazaar metadata"},
	{"_darcs/", "Darcs metadata"},
	{".jj/", "Jujutsu metadata (holds a git store)"},
	// Secrets: credential-shaped files are excluded by PlanManifest too;
	// listing them as ignored keeps them out of the candidate list at all.
	{".env*", "environment files, which usually hold secrets"},
	// Operating-system junk.
	{".DS_Store", "macOS folder metadata"},
	{"._*", "macOS AppleDouble resource files"},
	{".Spotlight-V100/", "macOS Spotlight index"},
	{".fseventsd/", "macOS file-event log"},
	{".Trashes/", "macOS trash on a volume"},
	{".Trash-*/", "Linux desktop trash on a volume"},
	{"Thumbs.db", "Windows thumbnail cache"},
	{"desktop.ini", "Windows folder settings"},
	{"$RECYCLE.BIN/", "Windows recycle bin on a volume"},
}

// UploadIgnoreFile renders the exclude file the non-repository listing reads:
// the default set, then the extra patterns (each on its own line, so an
// extra negated pattern can take a default back out). A pattern holding a
// line break or a NUL is dropped (the config validation refuses it first).
func UploadIgnoreFile(extra []string) []byte {
	var b strings.Builder
	b.WriteString("# Observer's default ignore set for a hosted upload of a folder that is not a git repository\n")
	for _, r := range DefaultUploadIgnore {
		b.WriteString(r.Pattern)
		b.WriteByte('\n')
	}
	b.WriteString("# [terminal.sandbox.hosted].upload_ignore\n")
	for _, p := range extra {
		p = strings.TrimSpace(p)
		if p == "" || strings.ContainsAny(p, "\r\n\x00") {
			continue
		}
		b.WriteString(p)
		b.WriteByte('\n')
	}
	return []byte(b.String())
}

// NonRepositoryScopeKey names the upload scope of a folder that is not a
// repository: the repository-mode key's inputs (rule version, root, caps)
// plus the rendered ignore file and every uploaded path. Unlike a
// repository, whose file set git's index names, a plain folder's file set is
// only what the listing found, so consent is bound to it: a file added or
// removed re-asks, an edit to a file's content does not.
func NonRepositoryScopeKey(root string, lim ManifestLimits, extra []string, files []ManifestFile) string {
	h := sha256.New()
	fmt.Fprintf(h, "nongit-v1\x00%s\x00", ScopeKey(root, false, lim))
	h.Write(UploadIgnoreFile(extra))
	for _, f := range files {
		h.Write([]byte{0})
		h.Write([]byte(path.Clean(f.Path)))
	}
	return "nongit:" + hex.EncodeToString(h.Sum(nil))[:32]
}
