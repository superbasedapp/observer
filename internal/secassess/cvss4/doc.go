// Package cvss4 scores the base metrics of a CVSS 4.0 vector. It is the pure
// scoring core behind the CVSS line of a pen-test finding in the security
// assessments module (docs/plans/security-assessments-depth-plan-2026-11-14.md
// W7.1, decision D30).
//
// Scope. Base metrics only: AV, AC, AT, PR, UI, VC, VI, VA, SC, SI and SA. A
// copy of an application in an assessment box has no threat intelligence and
// no deployment, so Exploit Maturity is taken as Attacked and the three
// security requirements as High, the values the specification gives a vector
// that does not define them. A vector that carries any other metric, any
// metric out of order, a missing metric, an unknown value or a different
// version prefix is refused; nothing is guessed or dropped silently.
//
// Tables. The score data (the 270 valid MacroVector scores, the maximal
// vectors of each EQ level, the maximal severity distances and the per-metric
// severity levels) is in tables_gen.go, generated by tools/cvss4gen from a
// pinned copy of FIRST's calculator source (BSD-2-Clause; the notice is in the
// generated file and in THIRD_PARTY_NOTICES.md). Nothing in it is typed by
// hand. The algorithm in score.go is the one in FIRST's cvss_score.js,
// including its floating-point behaviour, and is checked against independent
// implementations and published scores (testdata/README.md).
//
// The package imports only the standard library (imports_test.go): no
// database, network, subprocess, filesystem or other observer package.
package cvss4

