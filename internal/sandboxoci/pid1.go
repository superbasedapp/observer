package sandboxoci

// pid1.go is the PID 1 contract of the in-container init (sandbox plan v2
// section 4.6, "The guest helper as the container's main process";
// JSP-4). The agent runs as the container's main TTY process so the engine
// attach can re-attach to it, which makes the entrypoint PID 1 in the
// container's PID namespace: default signal dispositions do not apply to it
// and orphans reparent to it. The rules, as data the init in cmd/observer
// walks:
//
//   - it reaps every child it inherits, so no zombie accumulates;
//   - it starts the inner launch in its OWN process group inside PID 1's
//     session (setpgid) and makes that group the TTY's foreground
//     (tcsetpgrp), ignoring SIGTTOU and SIGTTIN itself. Never setsid: the
//     TTY is already PID 1's controlling terminal and taking it for a new
//     session needs TIOCSCTTY with CAP_SYS_ADMIN, which the container has
//     dropped (JSP-4 measured exit 127 on every engine);
//   - Ctrl-C reaches the agent through the TTY's line discipline, never
//     through PID 1;
//   - it forwards SIGTERM, SIGHUP and SIGWINCH it receives from the engine
//     to the inner launch's group;
//   - it exits with the inner launch's status (128 plus the signal for a
//     signalled exit).

// InitPlan is the contract, as plain data.
type InitPlan struct {
	// ForwardToGroup are the signals PID 1 forwards to the inner launch's
	// process group.
	ForwardToGroup []string
	// Ignore are the signals PID 1 ignores (job control on the terminal it
	// hands to the agent's group).
	Ignore []string
	// TerminalSignals are generated by the TTY for the foreground group;
	// PID 1 is never in that group, so they never reach it.
	TerminalSignals []string
	// NewProcessGroup: the inner launch gets its own group (setpgid).
	NewProcessGroup bool
	// NewSession is always false in a container (see above).
	NewSession bool
	// Foreground: the inner launch's group becomes the TTY's foreground.
	Foreground bool
	// ReapAll: PID 1 waits for every child, not only the inner launch.
	ReapAll bool
}

// ContainerInit is the contract the container entrypoint follows.
func ContainerInit() InitPlan {
	return InitPlan{
		ForwardToGroup:  []string{"SIGTERM", "SIGHUP", "SIGWINCH"},
		Ignore:          []string{"SIGTTOU", "SIGTTIN"},
		TerminalSignals: []string{"SIGINT", "SIGQUIT", "SIGTSTP"},
		NewProcessGroup: true,
		NewSession:      false,
		Foreground:      true,
		ReapAll:         true,
	}
}

// ExitCode maps the inner launch's end to PID 1's exit status: its own
// code, or 128 plus the signal when it was killed by one.
func ExitCode(exited bool, code int, signaled bool, signal int) int {
	switch {
	case signaled:
		return 128 + signal
	case exited:
		return code
	}
	return 255
}

// WaitCondition is the condition the host helper waits on. It is opened
// BEFORE start (JSP-4): "next-exit" returns the status of the run that is
// about to start; "not-running" would return at once for a created
// container.
const WaitCondition = "next-exit"

// HelperAction is something the host helper may do to its container.
type HelperAction string

// The HelperAction values.
const (
	ActionAttach HelperAction = "attach"
	ActionSignal HelperAction = "signal"
	ActionStop   HelperAction = "stop"
	ActionResize HelperAction = "resize"
	ActionRemove HelperAction = "remove"
)

// Allowed is the exit-status rule of section 4.6: the helper never
// attaches to, signals, resizes or stops a container whose state is not
// running, because on Podman an attach to an exited container re-initialises
// it (4.9.3 reported "created, 0" for one that exited 7) and a stop rewrites
// its exit code (143 on 4.9.3, 2 on 5.6.2). Removing is always allowed: it
// is the teardown, after the status was kept.
func Allowed(a HelperAction, running bool) bool {
	if a == ActionRemove {
		return true
	}
	return running
}
