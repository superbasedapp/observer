// TestHarnessPromptKind walks the recognition table (T-966), one case per
// shape, including the near misses that must stay the developer's prompt.
func TestHarnessPromptKind(t *testing.T) {
	cases := []struct {
		name     string
		text     string
		wantKind string
		injected bool
	}{
		{"task notification", "<task-notification>\n<task-id>x</task-id>", harnessKindTaskEvent, true},
		{"task notification after whitespace", "  \n<task-notification>", harnessKindTaskEvent, true},
		{"agent hand-back with attributes", `<agent-message from="lead">[hand-back]`, harnessKindAgentMessage, true},
		{"system reminder", "<system-reminder>ctx</system-reminder>", harnessKindPromptContext, true},
		{"slash command envelope", "<command-name>/clear</command-name>", harnessKindPromptContext, true},
		{"local command stdout", "<local-command-stdout>ok</local-command-stdout>", harnessKindPromptContext, true},
		{"bash stdout", "<bash-stdout>secret</bash-stdout>", harnessKindPromptContext, true},
		{"ide opened file", "<ide_opened_file>The user opened /x</ide_opened_file>", harnessKindPromptContext, true},
		{"fork boilerplate", "<fork-boilerplate>", harnessKindPromptContext, true},
		{"self-closing tag", "<uploaded_files/>", harnessKindPromptContext, true},
		{"caveat text", "Caveat: the messages below were generated by the user", harnessKindPromptContext, true},
		{"plain prompt", "Fix the retry loop", "", false},
		{"prompt mentioning a tag later", "Why does <task-notification> show up?", "", false},
		{"longer tag name is not a match", "<task-notifications>", "", false},
		{"unknown tag stays a prompt", "<pasted_content>my notes</pasted_content>", "", false},
		{"lone angle bracket", "< task-notification>", "", false},
		{"empty", "", "", false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			kind, injected := HarnessPromptKind(tc.text)
			if kind != tc.wantKind || injected != tc.injected {
				t.Fatalf("HarnessPromptKind(%q) = (%q, %v), want (%q, %v)", tc.text, kind, injected, tc.wantKind, tc.injected)
			}
			if got := isHarnessPrompt(tc.text); got != tc.injected {
				t.Fatalf("isHarnessPrompt = %v, want %v", got, tc.injected)
			}
		})
	}
}

// TestHarnessKindsAreKnownActionKinds pins that every re-label target survives
// the activity mix's closed allow-list as itself (never "unclassified").
func TestHarnessKindsAreKnownActionKinds(t *testing.T) {
	for _, rules := range [][]harnessPromptRule{harnessPromptRules, harnessPromptTextPrefixes} {
		for _, r := range rules {
			if !knownActionKinds[r.Kind] {
				t.Errorf("rule %q re-labels to %q, which is not a known action kind", r.Tag, r.Kind)
			}
		}
	}
}

// TestReclassifyPromptKind re-labels only user_prompt rows.
func TestReclassifyPromptKind(t *testing.T) {
	cases := []struct{ kind, text, want string }{
		{"user_prompt", "<task-notification>", harnessKindTaskEvent},
		{"user_prompt", "Fix it", "user_prompt"},
		{"assistant_message", "<task-notification>", "assistant_message"},
		{"run_command", "<bash-stdout>", "run_command"},
	}
	for _, tc := range cases {
		if got := ReclassifyPromptKind(tc.kind, tc.text); got != tc.want {
			t.Errorf("ReclassifyPromptKind(%q, %q) = %q, want %q", tc.kind, tc.text, got, tc.want)
		}
	}
}

// TestHarnessPromptTallyReclassify moves counts out of user_prompt, never
// below zero, without touching the input.
func TestHarnessPromptTallyReclassify(t *testing.T) {
	cases := []struct {
		name  string
		heads []string
		mix   []ActivityMixInput
		want  []ActivityMixInput
	}{
		{
			name:  "nothing injected keeps the mix",
			heads: []string{"Fix it", "Add a test"},
			mix:   []ActivityMixInput{{"edit_file", 3}, {"user_prompt", 2}},
			want:  []ActivityMixInput{{"edit_file", 3}, {"user_prompt", 2}},
		},
		{
			name:  "injected rows move to their kinds",
			heads: []string{"<task-notification>", "<task-notification>", `<agent-message from="a">`, "<system-reminder>", "Fix it"},
			mix:   []ActivityMixInput{{"edit_file", 3}, {"user_prompt", 5}},
			want: []ActivityMixInput{
				{"edit_file", 3},
				{"user_prompt", 1},
				{harnessKindTaskEvent, 2},
				{harnessKindAgentMessage, 1},
				{harnessKindPromptContext, 1},
			},
		},
		{
			name:  "all injected drops the user_prompt entry",
			heads: []string{"<task-notification>"},
			mix:   []ActivityMixInput{{"user_prompt", 1}},
			want:  []ActivityMixInput{{harnessKindTaskEvent, 1}},
		},
		{
			name:  "a tally larger than the entry never goes negative",
			heads: []string{"<task-notification>", "<task-notification>", "<system-reminder>"},
			mix:   []ActivityMixInput{{"user_prompt", 2}},
			want:  []ActivityMixInput{{harnessKindTaskEvent, 2}},
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			var tally HarnessPromptTally
			for _, h := range tc.heads {
				tally.Add(h)
			}
			orig := append([]ActivityMixInput(nil), tc.mix...)
			got := tally.Reclassify(tc.mix)
			if !reflect.DeepEqual(got, tc.want) {
				t.Fatalf("Reclassify = %+v, want %+v", got, tc.want)
			}
			if !reflect.DeepEqual(tc.mix, orig) {
				t.Fatalf("Reclassify modified its input: %+v", tc.mix)
			}
		})
	}
}

// TestSelectExcerptsSkipsHarnessMessages is the excerpt half of T-966 with
// the live shapes: a task notification carrying a local path and a request id
// is never the first prompt and never a sampled prompt.
func TestSelectExcerptsSkipsHarnessMessages(t *testing.T) {
	texts := SessionTexts{UserPrompts: []string{
		"<task-notification>\n<task-id>b7</task-id>\n<output-file>/home/dev/x.output</output-file>\n<summary>req_01HZ done</summary>\n</task-notification>",
		"Make the retry loop back off.",
		`<agent-message from="lead">see /home/dev/notes.md</agent-message>`,
		"Add a jitter test.",
	}}
	for _, titleOnly := range []bool{true, false} {
		out := SelectExcerpts(texts, titleOnly)
		if len(out) == 0 || out[0].Source != SourceFirstUserPrompt || out[0].Text != "Make the retry loop back off." {
			t.Fatalf("titleOnly=%v: first excerpt = %+v", titleOnly, out)
		}
		for _, e := range out {
			if strings.Contains(e.Text, "/home/dev") || strings.Contains(e.Text, "req_01HZ") {
				t.Fatalf("titleOnly=%v: harness text excerpted: %q", titleOnly, e.Text)
			}
		}
	}
	sel := SelectExcerptsWithSettings(texts, ExcerptSelection{UserMessages: 10, Bytes: 1024})
	if len(sel) != 2 {
		t.Fatalf("SelectExcerptsWithSettings kept %d prompts, want the 2 real ones: %+v", len(sel), sel)
	}
}
