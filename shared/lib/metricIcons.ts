/** MetricKey names one KPI metric in {@link METRIC_ICONS}. */
export type MetricKey = keyof typeof METRIC_ICONS;

/** metricIcon returns the one glyph for a KPI metric. */
export function metricIcon(metric: MetricKey): LucideIcon {
  return METRIC_ICONS[metric];
}
