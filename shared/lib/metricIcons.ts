// METRIC_ICONS: the ONE metric -> glyph table for every KPI tile in the node
// dashboard (StatCard / HeroStat / BigStat). Pages name the METRIC a tile
// shows, never a glyph, so the same metric carries the same icon on every
// page ("sessions" is MessagesSquare on Overview, Analysis, Compression and
// Cost alike) and two different metrics never share one (pinned by
// metricIcons.test.ts). Before this table the Coins / Bolt / Droplet /
// Sparkles glyphs were reused across unrelated tiles (Cache Read and Cache
// Write both Droplet, Output and Reasoning both Sparkles).
//
// A tile that shows the same metric over a different window or scope
// (Verdicts 24h / 7d, Mispredict rate / Anthropic mispredict rate) uses the
// same key on purpose: it is one metric, so it keeps one glyph.
//
// Shared by every app (moved from web/src/lib 2026-09-28) so a metric has the
